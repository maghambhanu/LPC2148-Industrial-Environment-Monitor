//TYPES.H
typedef unsigned char u8;         // Alias for 8-bit unsigned integer (0 to 255)
typedef char s8;                  // Alias for 8-bit signed character/integer (-128 to 127)
typedef unsigned short u16;       // Alias for 16-bit unsigned integer (0 to 65,535)
typedef short s16;                // Alias for 16-bit signed integer (-32,768 to 32,767)
typedef unsigned int  u32;        // Alias for 32-bit unsigned integer
typedef int s32;                  // Alias for 32-bit signed integer
typedef float f32;                // Alias for 32-bit single-precision floating-point number
typedef double f64;               // Alias for 64-bit double-precision floating-point number
